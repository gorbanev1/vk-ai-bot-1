import assert from 'node:assert/strict';
import {TELEGRAM_MENU_BUTTONS as B,TELEGRAM_OWNER_MAIN_MENU,resolveTelegramMenuInput} from '../../src/platforms/telegram/telegramBot.js';
const buttons=TELEGRAM_OWNER_MAIN_MENU.keyboard.flat().map(b=>b.text);
assert.ok(buttons.includes(B.imageMenu));
assert.ok(!buttons.includes(B.image));
assert.ok(!buttons.includes(B.imageEdit));
const root=resolveTelegramMenuInput(B.imageMenu,{}, {isOwner:true});
assert.equal(root.state.menuPath,'image-section');
const inside=root.replyMarkup.keyboard.flat().map(b=>b.text);
assert.ok(inside.includes(B.image));
assert.ok(inside.includes(B.imageEdit));
const choices=resolveTelegramMenuInput(B.image,root.state,{isOwner:true});
assert.equal(choices.state.menuPath,'image-models');
const generated=resolveTelegramMenuInput(B.imageModel25,choices.state,{isOwner:true});
assert.equal(generated.state.pendingAction,'image');
const edit=resolveTelegramMenuInput(B.imageEdit,root.state,{isOwner:true});
assert.equal(edit.state.menuPath,'image-models');
const selectedEdit=resolveTelegramMenuInput(B.imageModel25,edit.state,{isOwner:true});
assert.equal(selectedEdit.state.pendingAction,'image_edit');
assert.equal(selectedEdit.state.imageEditMode,true);
const fromPrompt=resolveTelegramMenuInput(B.back,selectedEdit.state,{isOwner:true});
assert.equal(fromPrompt.state.menuPath,'image-models');
const fromModels=resolveTelegramMenuInput(B.back,fromPrompt.state,{isOwner:true});
assert.equal(fromModels.state.menuPath,'image-section');
const toMain=resolveTelegramMenuInput(B.back,fromModels.state,{isOwner:true});
assert.ok(!toMain.state.menuPath);
assert.ok(toMain.replyMarkup.keyboard.flat().some(b=>b.text===B.imageMenu));
console.log('Telegram images submenu passed');
