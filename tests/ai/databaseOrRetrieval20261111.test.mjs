import assert from 'node:assert/strict';
import {parseDatabaseMessageRetrievalQuery as parse,messageTextMatchesRetrievalTerm as match}
    from '../../src/features/ai/globalWhoDatabaseRouting.js';
const q='Гигорейв найди в переписке какие инциденты были с Владиславом или Владислейвом';
const result=parse(q);
assert.equal(result.matched,true);
assert.equal(result.kind,'conversation-analysis');
assert.equal(result.scope,'current-peer');
const terms=result.searchTerms.map(x=>x.toLocaleLowerCase('ru-RU'));
assert.ok(terms.includes('владислав'),JSON.stringify(terms));
assert.ok(terms.includes('владислейв'),JSON.stringify(terms));
assert.ok(terms.includes('владислэйв'),JSON.stringify(terms));
assert.ok(!terms.some(x=>/инцидент|переписк|или|были|гигорейв/u.test(x)),JSON.stringify(terms));
const isMatch=text=>result.searchTerms.some(term=>match(text,term));
assert.equal(isMatch('Владислав заходил вечером'),true);
assert.equal(isMatch('Поговорили с Владиславом'),true);
assert.equal(isMatch('На вечеринке упомянули Владислейва'),true);
assert.equal(isMatch('На вечеринке упомянули Владислэйва'),true);
assert.equal(isMatch('Никаких имён сегодня не называли'),false);
const many=parse('Гигорейв, найди в переписке инциденты с Владиславом или Владислэйвом или Максом');
assert.ok(many.searchTerms.some(x=>/^макс/iu.test(x)),JSON.stringify(many));
const single=parse('Гигорейв найди в переписке какие инциденты были с Владиславом');
assert.ok(single.searchTerms.some(x=>/^владислав$/iu.test(x)),JSON.stringify(single));
const broad=parse('Гигорейв проанализируй переписку');
assert.equal(broad.matched,true);
assert.deepEqual(broad.searchTerms,[]);
const topical=parse('Гигорейв проанализируй переписку про ЕВИК');
assert.deepEqual(topical.searchTerms,['ЕВИК']);
console.log('Specific names and OR alternatives: targeted search, not whole-chat scan');
