// Текст рубрики «Чтиво» для отправки обычным сообщением VK.
const NIZSHIY_PILOTAZH_ANNOTATION = 'Баян Ширянов (настоящее имя — Кирилл Воробьёв, 1964–2017) — российский писатель и журналист, известный своими провокационными произведениями о жизни людей на социальном дне. Наибольшую известность ему принёс роман «Низший пилотаж», впервые опубликованный в интернете в 1996 году. Произведение посвящено жизни московских наркозависимых 1990-х годов и рассказывает об их повседневности, поисках наркотиков, галлюцинациях и постепенном разрушении личности. Через историю главного героя автор исследует темы зависимости, одиночества, свободы и попыток бегства от реальности. Роман отличается грубым языком, чёрным юмором, натуралистичностью и использованием наркотического жаргона. Благодаря откровенному изображению запрещённой субкультуры книга вызвала общественные споры: одни считали её смелым литературным экспериментом, другие обвиняли в пропаганде наркотиков. Впоследствии роман стал первой частью трилогии, продолженной произведениями «Срединный пилотаж» и «Верховный пилотаж».';

export function formatChtivoIntroduction(book) {
  const title = String(book?.title || '').trim();
  const introduction = [
    'С вами рубрика Гигорейв чтиво.',
    `Вам будет представлен отрывок из произведения «${title}».`,
    'Приятного прочтения.',
  ];
  if (title.toLocaleLowerCase('ru').replace(/ё/g, 'е') === 'низший пилотаж') {
    introduction.push('Краткая аннотация :', NIZSHIY_PILOTAZH_ANNOTATION);
  }
  return introduction.join('\n\n');
}
