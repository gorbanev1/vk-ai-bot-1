function normalizeRandomUnit(value) {
    const number = Number(value);

    if (!Number.isFinite(number)) {
        return 0;
    }

    return Math.min(0.999999999, Math.max(0, number));
}

function selectOutburstScenario(random = Math.random) {
    const value = normalizeRandomUnit(random());

    if (value < OUTBURST_SCENARIO_WEIGHTS.conversation) {
        return 'conversation';
    }

    if (
        value <
        OUTBURST_SCENARIO_WEIGHTS.conversation + OUTBURST_SCENARIO_WEIGHTS.air
    ) {
        return 'air';
    }

    return 'participant';
}

function selectActiveBehaviorModelMode(random = Math.random) {
    return normalizeRandomUnit(random()) < 0.5 ? 'pro' : 'pro2';
}

function buildRandomOutburst({
    persona,
    scenario = 'air',
    targetName,
    random = Math.random,
} = {}) {
    const personaKey = isOutburstPersona(persona) ? persona : 'durachila';
    const scenarioKey = ['conversation', 'air', 'participant'].includes(scenario)
        ? scenario
        : 'air';
    const templates = OUTBURST_TEMPLATES[personaKey][scenarioKey];
    const index = Math.min(
        templates.length - 1,
        Math.max(0, Math.floor(normalizeRandomUnit(random()) * templates.length)),
    );
    const safeName = String(targetName ?? 'товарищ')
        .replace(/[\r\n]+/gu, ' ')
        .trim()
        .slice(0, 80) || 'товарищ';

    return templates[index].replace('{name}', safeName);
}

