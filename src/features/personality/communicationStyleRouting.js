const PERSONA_ALIAS_MAP = new Map();

for (const [persona, definition] of Object.entries(PERSONA_DEFINITIONS)) {
    for (const alias of definition.aliases) {
        PERSONA_ALIAS_MAP.set(normalizeStyleText(alias), persona);
    }
}

function normalizeStyleText(value) {
    return String(value ?? '')
        .toLowerCase()
        .replace(/ё/gu, 'е')
        .replace(/[«»"'`]/gu, '')
        .replace(/[,:;!?]+/gu, ' ')
        .replace(/\s+/gu, ' ')
        .trim();
}

function clampWarmth(value, fallback = 5) {
    const number = Number(value);

    if (!Number.isFinite(number)) {
        return fallback;
    }

    return Math.min(10, Math.max(1, Math.round(number)));
}

function escapeRegExp(value) {
    return String(value).replace(/[.*+?^${}()|[\]\\]/gu, '\\$&');
}

function findPersonaInText(normalized) {
    const aliases = [...PERSONA_ALIAS_MAP.keys()]
        .sort((left, right) => right.length - left.length);

    for (const alias of aliases) {
        const expression = new RegExp(`(?:^|\\s)${escapeRegExp(alias)}(?:$|\\s)`, 'u');

        if (expression.test(normalized)) {
            return PERSONA_ALIAS_MAP.get(alias) ?? null;
        }
    }

    return null;
}

function parseWarmth(normalized) {
    const expressions = [
        /(?:температур(?:а|ы|у|е|ой)?|теплот(?:а|ы|у|е|ой)?|расположенност(?:ь|и|ью)?)(?:\s+общени(?:я|ю|е|й))?\s*(?:на|=)?\s*(10|[1-9])(?:\s*(?:из|\/|по)\s*10)?(?:$|\s)/u,
        /(?:общайся|отвечай|разговаривай)(?:\s+со\s+мной|\s+с\s+нами)?\s+(?:с\s+теплотой|по\s+теплоте|по\s+расположенности)\s*(?:на)?\s*(10|[1-9])(?:\s*(?:из|\/|по)\s*10)?(?:$|\s)/u,
        /(?:теплее|холоднее)\s*(?:на)?\s*(10|[1-9])(?:\s*(?:из|\/|по)\s*10)?(?:$|\s)/u,
    ];

    for (const expression of expressions) {
        const match = normalized.match(expression);

        if (match) {
            return clampWarmth(match[1]);
        }
    }

    return null;
}

function parseCommunicationStyleCommand(value) {
    const normalized = normalizeStyleText(value);

    if (!normalized) {
        return { matched: false, action: 'none', warmth: null, persona: null };
    }

    if (
        /^(?:покажи\s+|какой\s+|какая\s+)?(?:стиль|стиль\s+общения|температура\s+общения|теплота\s+общения)(?:\s+сейчас)?$/u.test(normalized) ||
        /^(?:как\s+ты\s+сейчас\s+общаешься|настройки\s+общения)$/u.test(normalized)
    ) {
        return { matched: true, action: 'status', warmth: null, persona: null };
    }

    if (
        /^(?:сбрось|сбросить|очисти|очистить|верни)\s+(?:стиль|настройки\s+общения|обычный\s+стиль)$/u.test(normalized) ||
        /^(?:будь|стань)\s+(?:обычным|нормальным|нейтральным)$/u.test(normalized) ||
        /^(?:обычный|нейтральный)\s+стиль$/u.test(normalized)
    ) {
        return { matched: true, action: 'reset', warmth: 5, persona: 'neutral' };
    }

    const warmth = parseWarmth(normalized);
    const persona = findPersonaInText(normalized);
    const commandPrefix = /^(?:(?:пожалуйста|теперь|сейчас|отныне)\s+)*(?:(?:поставь|установи|задай|сделай|измени)\s+)?/u;
    const personaCommandExpression = new RegExp(
        `${commandPrefix.source}(?:будь|стань|общайся|разговаривай|отвечай|стиль)(?:$|\\s)`,
        'u',
    );
    const warmthCommandExpression = new RegExp(
        `${commandPrefix.source}(?:температур|теплот|расположенност|общайся|отвечай|разговаривай)`,
        'u',
    );
    const hasPersonaCommand = Boolean(persona && personaCommandExpression.test(normalized));
    const hasWarmthCommand = Boolean(warmth !== null && warmthCommandExpression.test(normalized));

    if (!hasPersonaCommand && !hasWarmthCommand) {
        return { matched: false, action: 'none', warmth: null, persona: null };
    }

    return {
        matched: true,
        action: 'set',
        warmth,
        persona: hasPersonaCommand ? persona : null,
    };
}

function buildWarmthInstruction(warmth) {
    const level = clampWarmth(warmth);

    if (level <= 2) {
        return `Теплота и расположенность: ${level}/10. Общайся холодно, отстранённо и без утешительного сервисного тона. Не добавляй комплименты, заботливые оговорки и дружеские заигрывания.`;
    }

    if (level <= 4) {
        return `Теплота и расположенность: ${level}/10. Общайся суховато и дистанцированно, но не враждебно.`;
    }

    if (level <= 6) {
        return `Теплота и расположенность: ${level}/10. Общайся ровно, естественно и умеренно доброжелательно.`;
    }

    if (level <= 8) {
        return `Теплота и расположенность: ${level}/10. Общайся тепло, заинтересованно и поддерживающе, сохраняя честность и конкретность.`;
    }

    return `Теплота и расположенность: ${level}/10. Общайся очень тепло, по-дружески и с явной симпатией; проявляй заботу и вовлечённость, но не льсти.`;
}

